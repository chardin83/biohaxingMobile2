// Usage: node scripts/importUsdaFoodCatalog.cjs /path/to/official/SRLegacyFoods.json
// Source: https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2018-04.zip
// Imports published nutrient amounts only. Missing nutrients are not treated as zero.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const mapping = require('../types/nutrition/usdaFoodMappings.json');
const input = process.argv[2];
if (!input) throw new Error('Pass the extracted USDA SR Legacy JSON file.');
const document = JSON.parse(fs.readFileSync(input, 'utf8'));
const foods = Array.isArray(document) ? document : document.SRLegacyFoods;
if (!Array.isArray(foods)) throw new Error('Expected an official SR Legacy dataset.');
const byNdb = new Map(foods.map(food => [Number(food.ndbNumber), food]));
const fields = {
  calories: '208', protein: '203', fat: '204', carbohydrates: '205', fiber: '291', caffeineMg: '262', alcoholGrams: '221',
};
const groups = {
  mineralsByType: { calcium: '301', iron: '303', magnesium: '304', phosphorus: '305', potassium: '306', sodium: '307', zinc: '309', copper: '312', manganese: '315', selenium: '317' },
  vitaminsByType: { vitamin_a: '320', vitamin_c: '401', vitamin_d: '328', vitamin_e: '323', vitamin_k: '430', vitamin_b1: '404', vitamin_b2: '405', vitamin_b3: '406', vitamin_b5: '410', vitamin_b6: '415', vitamin_b9: '417', vitamin_b12: '418' },
  // The app's cysteine key represents the USDA cystine quantity. Glutamic acid
  // is deliberately NOT mapped to glutamine; these are different compounds.
  aminoAcidsByType: { tryptophan: '501', threonine: '502', isoleucine: '503', leucine: '504', lysine: '505', methionine: '506', cysteine: '507', phenylalanine: '508', tyrosine: '509', valine: '510', arginine: '511', histidine: '512', glycine: '516', proline: '517', tmg: '454' },
};
function amount(nutrients, number, targetUnit) {
  const found = nutrients.get(number);
  if (!found || typeof found.amount !== 'number' || !Number.isFinite(found.amount) || found.amount < 0) return undefined;
  const unit = found.nutrient.unitName.toLowerCase().replace('μ', 'µ');
  const factors = { g: 1000, mg: 1, 'µg': 0.001, ug: 0.001 };
  if (unit === targetUnit) return found.amount;
  if (targetUnit !== 'mg' || !(unit in factors)) throw new Error(`Unexpected USDA unit ${unit} for nutrient ${number}`);
  return Number((found.amount * factors[unit]).toPrecision(12));
}
const profiles = {}, sources = {};
for (const [key, ndb] of Object.entries(mapping)) {
  const food = byNdb.get(ndb);
  if (!food) throw new Error(`Missing USDA NDB ${ndb} (${key})`);
  const nutrients = new Map(food.foodNutrients.map(n => [n.nutrient.number, n]));
  const record = {};
  for (const [field, number] of Object.entries(fields)) {
    const unit = field === 'calories' ? 'kcal' : field === 'caffeineMg' ? 'mg' : 'g';
    const value = amount(nutrients, number, unit);
    if (value !== undefined) record[field] = value;
  }
  for (const required of ['calories', 'protein', 'fat', 'carbohydrates']) {
    if (record[required] === undefined) throw new Error(`${key} lacks USDA ${required}; do not manufacture zero values.`);
  }
  // Same measured total, mapped to the app's fibre categories without estimating subtypes.
  if (record.fiber !== undefined) record.fiberByType = { fiber_total: record.fiber };
  for (const [group, members] of Object.entries(groups)) {
    const values = {};
    for (const [field, number] of Object.entries(members)) {
      const value = amount(nutrients, number, 'mg');
      if (value !== undefined) values[field] = value;
    }
    if (Object.keys(values).length) record[group] = values;
  }
  profiles[key] = record;
  sources[key] = { ndbNumber: ndb, fdcId: food.fdcId, description: food.description };
}
const format = value => JSON.stringify(value, null, 2);
let output = "import type { NutritionComposition } from './nutritionProfile';\n\n";
output += '// Generated by scripts/importUsdaFoodCatalog.cjs from USDA SR Legacy, April 2018.\n';
output += '// Per 100 g edible portion: macros/fibre/alcohol in g; vitamins/minerals/amino acids/caffeine in mg.\n';
output += '// Only values actually published in the dataset are included.\n';
output += 'export const USDA_FOOD_NUTRIENT_PROFILES = {\n';
for (const [key, record] of Object.entries(profiles)) {
  output += `  // USDA NDB ${sources[key].ndbNumber}: ${sources[key].description}\n`;
  output += `  ${key}: ${format(record).replace(/\n/g, '\n  ')},\n`;
}
output += '} satisfies Record<string, Partial<NutritionComposition>>;\n\n';
output += `export const USDA_FOOD_SOURCES = ${format(sources)} as const;\n`;
fs.writeFileSync(path.join(__dirname, '../types/nutrition/foodCatalog.ts'), output);
// Remove only values present in USDA, retaining unmatched nutrients and metadata.
const extraPath = path.join(__dirname, '../types/nutrition/foodCatalogSupplementary.ts');
const extraText = fs.readFileSync(extraPath, 'utf8');
const ast = ts.createSourceFile(extraPath, extraText, ts.ScriptTarget.Latest, true);
const declaration = ast.statements.filter(ts.isVariableStatement)
  .flatMap(statement => [...statement.declarationList.declarations])
  .find(node => node.name.getText(ast) === 'FOOD_SUPPLEMENTARY_PROFILES');
if (!declaration) throw new Error('Missing supplementary profile declaration.');
let object = declaration.initializer;
while (!ts.isObjectLiteralExpression(object)) object = object.expression;
const supplementaryEntries = object.properties.map(property => {
  const key = property.name.getText(ast);
  if (!profiles[key]) return `  ${property.getText(ast)},`;
  const retained = [];
  for (const field of property.initializer.properties) {
    const fieldName = field.name.getText(ast);
    if (!Object.hasOwn(profiles[key], fieldName)) {
      retained.push(field.getFullText(ast).trim());
    } else if (ts.isObjectLiteralExpression(field.initializer)) {
      const remaining = field.initializer.properties.filter(member => !Object.hasOwn(profiles[key][fieldName], member.name.getText(ast)));
      if (remaining.length) retained.push(`${fieldName}: { ${remaining.map(member => member.getFullText(ast).trim()).join(', ')} }`);
    }
  }
  return `  ${key}: {\n    ${retained.join(',\n    ')}\n  },`;
});
const header = `import type { FoodNutrientProfile } from './foodCatalogTypes';\n\n` +
  '// Only nutrients absent from the matched USDA record, app metadata and estimates belong here.\n' +
  '// For foods with no reliable matching USDA preparation/product, the original profile is retained.\n' +
  '// Such legacy amounts are unverified; this file does not establish nutritional provenance.\n' +
  '// Independent fructan assays can exceed legacy total-fibre values. Do not add the two totals.\n';
fs.writeFileSync(extraPath, `${header}export const FOOD_SUPPLEMENTARY_PROFILES = {\n${supplementaryEntries.join('\n')}\n} satisfies Record<string, Partial<FoodNutrientProfile>>;\n`);
console.log(`Imported ${Object.keys(profiles).length} USDA NDB records.`);
